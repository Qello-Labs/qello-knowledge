"""질의 기록 저장소. 관리 조회·삭제는 질의 포트에 노출하지 않는다."""

from typing import Literal, Protocol

from qello_knowledge.domain.query_log import FeedbackValue, QueryDelivery, QueryRecord, SourcesView

FeedbackResult = Literal["stored", "missing"]
TextResult = Literal["stored", "exists", "missing", "not_questioner"]
TextStatus = Literal["stored", "none", "missing", "not_questioner"]


class QueryLog(Protocol):
    def insert(self, record: QueryRecord) -> None: ...
    def delivered(self, delivery: QueryDelivery) -> None: ...
    def feedback(self, run_id: str, rater_id: str, value: FeedbackValue) -> FeedbackResult: ...
    def store_question(self, run_id: str, questioner_id: str, question: str) -> TextResult: ...
    def mark_text_skipped(self, run_id: str) -> None: ...
    def question_status(self, run_id: str, questioner_id: str) -> TextStatus: ...
    def sources(self) -> SourcesView: ...
